#!/usr/bin/env node
// tokens.json -> app/src/main/java/com/abdllh/aura/ui/DesignTokens.kt: the values of ui/Palette.kt and ui/Tokens.kt, generated, so no
// colour or size is ever typed twice. One command after any change to tokens.json:
//   node design/tokens/gen_tokens_kt.mjs
// (The surfaces are baked from the same tokens by the design folder's gen_surfaces.py; scripts/install_surfaces.py brings them in.)
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url)), ROOT = resolve(HERE, '..', '..');
const T = JSON.parse(readFileSync(join(HERE, 'tokens.json'), 'utf8'));
const OUT = join(ROOT, 'app', 'src', 'main', 'java', 'com', 'abdllh', 'aura', 'ui', 'DesignTokens.kt');
const hex2 = v => Math.round(v).toString(16).padStart(2, '0').toUpperCase();
function argb(s) {
  s = String(s).trim();
  if (s.startsWith('#')) { const h = s.slice(1); return h.length === 6 ? 'FF' + h.toUpperCase() : h.slice(6).toUpperCase() + h.slice(0, 6).toUpperCase(); }
  const p = s.slice(s.indexOf('(') + 1, s.indexOf(')')).split(',').map(Number);
  return hex2((p.length > 3 ? p[3] : 1) * 255) + hex2(p[0]) + hex2(p[1]) + hex2(p[2]);
}
const isColour = v => typeof v === 'string' && /^(#|rgba?\()/.test(v);
// scrimRgb is three numbers for the bakes; here it is the flat scrim behind a Modal, at the alpha of section 5
const SCRIM_ALPHA = 0.6;
const colours = th => {
  const e = Object.entries(T.color[th]).filter(([, v]) => isColour(v)).map(([n, v]) => [n, argb(v)]);
  e.push(['scrim', hex2(SCRIM_ALPHA * 255) + T.color[th].scrimRgb.split(',').map(x => hex2(+x)).join('')]);
  return e;
};
const names = colours('night').map(([n]) => n);
let k = `// Generated by design/tokens/gen_tokens_kt.mjs from tokens.json. Do not edit: change tokens.json and run it again.
package com.abdllh.aura.ui

/** Every colour of one theme. Palette assigns one of the two instances; views recolour in place (ui/Look.kt). */
class ThemeColors(
${names.map(n => `    @JvmField val ${n}: Int`).join(',\n')}
)

/** The colours by name, of the theme that is loaded: Palette.ink. */
abstract class ColorTokens {
    @JvmField var c: ThemeColors = Tokens2.NIGHT
${names.map(n => `    val ${n}: Int get() = c.${n}`).join('\n')}
}

/** The text roles of section 3 by name, Type.dist: [size px, weight, line box px, size px when the UI is English, weight at night on moving screens]. */
abstract class TypeRoles {
`;
for (const [n, v] of Object.entries(T.type)) if (n !== '$') k += `    @JvmField val ${n} = Type.Role("${n}", ${v[0]}, ${v[1]}, ${v[2]}, ${v[3]}, ${T.typeNight[n] ?? v[1]})\n`;
k += `}

object Tokens2 {
`;
for (const th of ['night', 'day']) {
  k += `    @JvmField val ${th.toUpperCase()} = ThemeColors(\n` + colours(th).map(([n, v]) => `        ${n} = 0x${v}.toInt()`).join(',\n') + `\n    )\n`;
}
k += `
    /** from the font: every weight has ascent 1.085 em and descent 0.415 em. Baseline of a line box = top + line / 2 + 0.335 * size */
    const val FONT_ASCENT = 1.085f
    const val FONT_DESCENT = 0.415f

`;
for (const [n, v] of Object.entries(T.radius)) k += `    const val R_${n} = ${v}\n`;
const G = T.grid;
k += `
    const val STRIP_H = ${G.stripH}
    const val CONTENT_TOP = ${G.contentTop}
    const val CONTENT_BOTTOM = ${G.contentBottom}
    const val MARGIN_X = ${G.marginX}
    const val GUTTER = ${G.gutter}
    const val COLUMN_X = ${G.column.x}
    const val COLUMN_W = ${G.column.w}
    const val FREE_X = ${G.free.x}
    const val FREE_W = ${G.free.w}
    const val DOCK_Y = ${G.dock.y}
    const val DOCK_H = ${G.dock.h}
    const val ROW_CENTRE_Y = ${G.dock.rowCentreY}
`;
for (const [n, v] of Object.entries(G.rowCentresX)) k += `    const val X_${n} = ${v}\n`;
k += `    const val TOUCH_MIN = ${T.touch.min}\n    const val TOUCH_FREQUENT = ${T.touch.frequent}\n`;
const m = T.motion;
k += '\n';
for (const [n, v] of Object.entries(m.ms)) k += `    const val MS_${n} = ${v}L\n`;
for (const [n, v] of Object.entries(m.curve)) k += `    @JvmField val CURVE_${n} = floatArrayOf(${v.map(x => x + 'f').join(', ')})\n`;
for (const [n, v] of Object.entries(m.press)) k += `    const val PRESS_${n} = ${v}f\n`;
for (const [n, v] of Object.entries(m.spring)) k += `    @JvmField val SPRING_${n} = floatArrayOf(${v.map(x => x + 'f').join(', ')})\n`;
k += `    const val DRIVING_FACTOR = ${m.driving.factor}f\n}\n`;
writeFileSync(OUT, k);
console.log('DesignTokens.kt', k.length, 'bytes');
